"""Generates ui/weather-icon.slint: vector weather glyphs in a 100x100 design space.

Run from the repo root:  python tools/gen_weather_icon.py
Shapes are built from circles and rounded rects so they stay crisp at any size/DPI and can be themed.
"""
import math
from pathlib import Path

def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")

def circle(cx, cy, r):
    # Clockwise, so overlapping shapes union under the non-zero fill rule.
    return f"M {f(cx-r)} {f(cy)} A {f(r)} {f(r)} 0 1 1 {f(cx+r)} {f(cy)} A {f(r)} {f(r)} 0 1 1 {f(cx-r)} {f(cy)} Z"

def rrect(x, y, w, h, r):
    return (f"M {f(x+r)} {f(y)} L {f(x+w-r)} {f(y)} A {f(r)} {f(r)} 0 0 1 {f(x+w)} {f(y+r)} "
            f"L {f(x+w)} {f(y+h-r)} A {f(r)} {f(r)} 0 0 1 {f(x+w-r)} {f(y+h)} "
            f"L {f(x+r)} {f(y+h)} A {f(r)} {f(r)} 0 0 1 {f(x)} {f(y+h-r)} "
            f"L {f(x)} {f(y+r)} A {f(r)} {f(r)} 0 0 1 {f(x+r)} {f(y)} Z")

def cloud(cx, cy, s):
    """Cloud centred at (cx, cy) scaled by s; base cloud is centred on (50, 47)."""
    T = lambda x, y: (cx + (x - 50) * s, cy + (y - 47) * s)
    parts = []
    for (x, y, r) in [(38, 52, 17), (57, 41, 22), (74, 55, 14)]:
        tx, ty = T(x, y)
        parts.append(circle(tx, ty, r * s))
    rx, ry = T(21, 50)
    parts.append(rrect(rx, ry, 67 * s, 19 * s, 9.5 * s))
    return " ".join(parts)

def sun(cx, cy, r):
    body = circle(cx, cy, r)
    rays = []
    for i in range(8):
        a = i * math.pi / 4
        rays.append(f"M {f(cx+math.cos(a)*(r+7))} {f(cy+math.sin(a)*(r+7))} "
                    f"L {f(cx+math.cos(a)*(r+15))} {f(cy+math.sin(a)*(r+15))}")
    return body, " ".join(rays)

def moon(cx, cy, r):
    # Crescent = outer circle minus an offset inner circle, traced as two arcs.
    ox, oy, R = cx, cy, r
    ix, iy, ri = cx + r * 0.55, cy - r * 0.38, r * 0.82
    d = math.hypot(ix - ox, iy - oy)
    a = (R * R - ri * ri + d * d) / (2 * d)
    h = math.sqrt(R * R - a * a)
    px, py = ox + a * (ix - ox) / d, oy + a * (iy - oy) / d
    p1 = (px + h * (iy - oy) / d, py - h * (ix - ox) / d)
    p2 = (px - h * (iy - oy) / d, py + h * (ix - ox) / d)
    return (f"M {f(p1[0])} {f(p1[1])} A {f(R)} {f(R)} 0 1 0 {f(p2[0])} {f(p2[1])} "
            f"A {f(ri)} {f(ri)} 0 0 1 {f(p1[0])} {f(p1[1])} Z")

def lines(segs):
    return " ".join(f"M {f(a)} {f(b)} L {f(c)} {f(d)}" for a, b, c, d in segs)

SUN_FILL = "@radial-gradient(circle, #fde7a6 0%, #f2c766 100%)"
RAY = "#eec872"
MOON_FILL = "@linear-gradient(135deg, #ebe8dd 0%, #c6c1b2 100%)"

# (condition, day-only?) -> layers: (kind, commands, paint, stroke_width_units, opacity)
layers = []

def add(cond, day, kind, cmd, paint, sw=0, opacity=1.0):
    layers.append((cond, day, kind, cmd, paint, sw, opacity))

b, r = sun(50, 50, 21);   add("clear", True, "fill", b, SUN_FILL); add("clear", True, "stroke", r, RAY, 4.6)
add("clear", False, "fill", moon(50, 50, 26), MOON_FILL)

b, r = sun(38, 36, 15);   add("partly-cloudy", True, "stroke", r, RAY, 4.2); add("partly-cloudy", True, "fill", b, SUN_FILL)
add("partly-cloudy", False, "fill", moon(38, 36, 18), MOON_FILL)
add("partly-cloudy", None, "fill", cloud(58, 62, 0.78), "CLOUD")

add("cloudy", None, "fill", cloud(62, 40, 0.62), "CLOUD", opacity=0.55)
add("cloudy", None, "fill", cloud(48, 58, 0.86), "CLOUD")

add("fog", None, "fill", cloud(50, 42, 0.82), "CLOUD")
add("fog", None, "stroke", lines([(22, 74, 70, 74), (32, 86, 80, 86)]), "#9ea9ba", 5, 0.75)

add("drizzle", None, "fill", cloud(50, 40, 0.86), "CLOUD")
add("drizzle", None, "stroke", lines([(34, 72, 32, 80), (52, 72, 50, 80), (70, 72, 68, 80)]), "#9cc3e0", 4.5)

add("rain", None, "fill", cloud(50, 40, 0.86), "CLOUD")
add("rain", None, "stroke", lines([(34, 70, 29, 88), (52, 70, 47, 88), (70, 70, 65, 88)]), "#80b2d8", 5.0)

add("snow", None, "fill", cloud(50, 40, 0.86), "CLOUD")
add("snow", None, "fill", " ".join(circle(x, y, 4) for x, y in [(32, 76), (50, 84), (68, 76), (41, 92), (59, 92)]), "#c2dcee")

add("thunder", None, "fill", cloud(50, 38, 0.86), "CLOUD")
add("thunder", None, "fill", "M 54 62 L 40 82 L 50 82 L 45 98 L 64 74 L 53 74 L 60 62 Z",
    "@linear-gradient(180deg, #f6dc8e 0%, #e9b765 100%)")

out = ["// Generated by tools/gen_weather_icon.py. Do not edit by hand.",
       'import { Theme } from "theme.slint";', "",
       "export enum Condition { clear, partly-cloudy, cloudy, fog, drizzle, rain, snow, thunder }", "",
       "export component WeatherIcon {",
       "    in property <Condition> condition;",
       "    in property <bool> day: true;",
       "    property <length> u: min(self.width, self.height) / 100;", ""]
for cond, day, kind, cmd, paint, sw, opacity in layers:
    cond_expr = f"root.condition == Condition.{cond}"
    if day is True: cond_expr += " && root.day"
    if day is False: cond_expr += " && !root.day"
    paint_expr = "Theme.cloud" if paint == "CLOUD" else paint
    out.append(f"    if {cond_expr} : Path {{")
    out.append("        width: root.width; height: root.height;")
    out.append("        viewbox-width: 100; viewbox-height: 100;")
    out.append(f'        commands: "{cmd}";')
    if kind == "fill":
        out.append(f"        fill: {paint_expr};")
    else:
        out.append(f"        stroke: {paint_expr};")
        out.append(f"        stroke-width: root.u * {sw};")
        out.append("        stroke-line-cap: round;")
    if opacity != 1.0:
        out.append(f"        opacity: {opacity};")
    out.append("    }")
out.append("}")
Path("ui/weather-icon.slint").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote ui/weather-icon.slint ({len(layers)} layers)")
